type PackBlock = BlockDef & { readonly nameKey: PackI18nKey };

/** A full opaque cube with one texture, dropping itself. */
export const cube = (
  key: `block:${string}`,
  nameKey: PackI18nKey,
  texture: `tex:${string}`,
  hardness: number,
  sound: BlockDef['sound'],
  extra: Partial<PackBlock> = {},
): PackBlock => ({
  key,
  nameKey,
  shape: 'cube',
  pass: 'opaque',
  textures: { all: texture },
  collision: 'full',
  opaque: true,
  hardness,
  drops: 'self',
  sound,
  ...extra,
});

/** A cross-shaped plant that needs a block below and that anything placed replaces. */
const plant = (
  key: `block:${string}`,
  nameKey: PackI18nKey,
  texture: `tex:${string}`,
  extra: Partial<PackBlock> = {},
): PackBlock => ({
  key,
  nameKey,
  shape: 'cross',
  pass: 'cutout',
  textures: { all: texture },
  collision: 'none',
  opaque: false,
  replaceable: true,
  hardness: 0,
  drops: 'none',
  placement: { support: 'below' },
  sound: 'leaves',
  ...extra,
});

